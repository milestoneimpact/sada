/**
 * ما يُحسَب بالشيفرة قبل النشر (D-003 · D-004).
 *
 * ### مفتاحُ عدم التكرار ليس هنا — وهذا مقصود
 *
 * كان هنا `idempotencyKey(postId, scope)` = `sha256(post.id + ':' + scope)`،
 * وهي صيغةٌ **لا تُحسَب قبل أن يوجد المنشور** — فلا تمنع كتابةَ مسوّدتين
 * للمصدر نفسه. فحلّ محلَّها مفتاحٌ يُشتقُّ من المحتوى لا من المعرّف، وهو
 * عند كلِّ منتجٍ في ملفّه:
 *
 * | الصفّ | المفتاح | أين |
 * |---|---|---|
 * | `posts` | `draft:{source}:{platform}:{hash}` | `draft/job.ts` |
 * | `media` صورةً | `image:{post}:{hash8(text)}` | `image/job.ts` |
 *
 * والقاعدةُ هي التي تفصل (`UNIQUE`) لا الشيفرة: طلبان متزامنان يكتب
 * أحدُهما ويُردّ الآخرُ «موجود» — ولا يُدفع الثمنُ مرّتين.
 */

/**
 * هل يحوي النص رابطا؟ (D-003)
 *
 * يُحسب بالشيفرة لا بالنموذج: منشور برابط على X يكلف 0.200 دولار بدل
 * 0.015 — ثلاثة عشر ضعفا — فلا يُترك تقديره لنموذج لغوي.
 *
 * يلتقط `http(s)://` و `www.` والنطاق المجرد بامتداد معروف. والاحتياط
 * مقصود: عدّ ما ليس رابطا رابطا يُظهر تكلفة أعلى قبل الاعتماد، وعكسه
 * يُنفق بلا علم.
 */
const URL_PATTERN =
  /(https?:\/\/\S+)|(\bwww\.\S+)|(\b[a-z0-9-]+\.(com|net|org|io|co|sa|me|ai|app|dev|xyz|link)\b)/i

export function containsUrl(text: string): boolean {
  return URL_PATTERN.test(text)
}
