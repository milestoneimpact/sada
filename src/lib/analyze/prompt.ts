/** سياق الموسم يُحقن في رسالة المستخدم لا في النظاميّ، فيبقى الأخير مخبّأ. */
export function userPrompt(args: {
  readonly name: string
  readonly text: string
  readonly now: Date
}): string {
  return `التاريخ الآن: ${hijriContext(args.now)}

الموسم يغيّر ما يستحقّ النشر ومتى. خذه في حسبانك إن كان للمصدر صلة به، وتجاهله إن لم تكن — ولا تفتعل صلةً غير قائمة.

اسم المصدر: ${args.name}

النصّ:
---
${args.text}
---`
}
