/**
 * **كتالوجُ الأخطاء** (D-302 · GOV.UK content design · Yifrah، Microcopy): كلُّ خطأٍ يصل المالكَ من هنا، بجزأين لا يُفصَلان —
 * **ما وقع** و**ما تفعل**. «خطأٌ غيرُ متوقّع» ليس خطأً بل اعتذار؛ و«فشل الطلب (500)» لغةُ الخادم.
 *
 * ## لماذا كتالوج
 *
 * كانت الرسائلُ مبعثرةً في المسارات (ستّةٌ وستّون ردًّا بنغمة «bad»)، وبعضُها يقول ما وقع ولا يقول ما يُفعَل. والجملةُ التي تُكتب
 * مرّةً هنا تُراجَع مرّةً وتُحرَس مرّة: اختبارُ `catalog.test` يُسقط رسالةً بلا فعلٍ تالٍ، و`lexicon.test` يُسقط كلمةَ مطوّرٍ فيها.
 *
 * ## القاعدة
 *
 * `what` جملةٌ تامّة بنقطة تقول ما وقع (ولماذا إن عُرف)؛ `next` جملةٌ تامّة بفعل أمرٍ يقول ما يفعله المالك الآن. و`say()` يصلهما.
 * **والمفتاحُ ثابتٌ لا يُعاد استعمالُه بمعنًى آخر**: المسارُ يردّه في `error` ليُقرأ من الاختبار ومن السجلّ.
 */

export interface ErrorText {
  readonly what: string
  readonly next: string
}

