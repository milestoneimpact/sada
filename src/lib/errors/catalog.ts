  bad_sample: { what: 'عيّنةُ السرعة لا تُقرأ.', next: 'لا شيءَ عليك: المتصفّحُ يعيد القياسَ في الفتحة التالية.' },
  not_per_org: { what: 'هذا الإعدادُ عامٌّ لا يُكتب لعميلٍ بعينه.', next: 'غيّره من الإنفاق والحدود لمنظّمة المالك.' },
