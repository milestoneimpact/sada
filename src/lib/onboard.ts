/**
 * اليومُ الأوّل (D-108) — **خمسُ خطواتٍ لا واحدةٌ منها تُكتب بيد**.
 *
 * ## لماذا معالجٌ في نظامٍ يعمل
 *
 * صدى يبدأ **فارغا تماما**: لا مصدرَ ولا قناةَ ولا خطّة. **والرافدةُ تعرض
 * تسعةَ أقسامٍ كلُّها فارغة**، ولا تقول أيَّها أوّلا. فمن فتحها أوّلَ مرّةٍ
 * وجد نظاما كاملَ الشكل **لا يعرف من أين يمسكه**.
 *
 * ## وحالُ كلِّ خطوةٍ مشتقّةٌ من القاعدة — درسُ D-073 حرفا
 *
 * `M-10` نجت من نصفِ حارس: **جدولٌ مكتوبٌ بيدٍ شاخ وقال «مطلوبة الآن»
 * و‏٤٢ تشغيلَ نشرٍ ناجحا تقول غيرَ ذلك**.
 *
 * فلا خطوةَ هنا تحمل علمَ «تمّت» يُكتب أو يُخزَّن. **كلُّها تُحسَب من
 * حقائقَ تُقرأ مع الصفحة**: مصدرٌ في `sources`، وحسابٌ حيٌّ في `accounts`،
 * وخطّةٌ في `plans`، ومنشورٌ خرج من حال `draft`. **فما لا يقع لا يُعلَّم
 * واقعا، ولو مرّ عليه شهر.**
 *
 * ## ولا علامةَ صحٍّ على ما لم يُتحقَّق منه — D-061
 *
 * «وُضع المفتاح» ليست «عمل المفتاح». **والخطوةُ الأولى هنا اتّصالُ Drive،
 * ودليلُها مصدرٌ وُجد فعلا** — لا ضبطُ `DRIVE_FOLDER_ID`. فمعرّفُ مجلّدٍ
 * مكتوبٌ لمجلّدٍ لا يُقرأ **يُعلَّم صحّا كذبا**.
 *
 * ## ويختفي من تلقاء نفسه
 *
 * **ومعالجٌ يبقى بعد أن يُستغنى عنه يُقرأ عطلا**: من أتمّ الخمسَ ثمّ رآه
 * كلَّ صباحٍ ظنّ أنّ شيئا لم يُحفَظ.
 */

/** خطوةٌ في اليوم الأوّل — **ولا تحمل حالا تُخزَّن**. */
export interface Step {
  readonly id: string
  readonly title: string
  /** ما يقع إن تُركت — لا وصفٌ لما تفعله. */
  readonly why: string
  /** أين تقع — مرساةٌ في اللوحة أو مسار. */
  readonly go: string
  readonly done: boolean
  /**
   * سطرٌ يقول ما وُجد حين تتمّ، أو ما ينقص حين لا تتمّ.
   *
   * **ودليلٌ لا حكم**: «مصدران في Drive» تُقرأ ولا تُصدَّق على عمياء،
   * و«تمّت» تُصدَّق ولا تُراجَع.
   */
  readonly proof: string
}

/** الحقائقُ التي تُشتَقّ منها الخطوات — **كلُّها مقروءةٌ مع الصفحة أصلا**. */
export interface OnboardFacts {
  readonly sources: number
  readonly analyzed: number
  readonly liveAccounts: number
  readonly hasPlan: boolean
  /** منشورٌ خرج من حال `draft` — اعتُمد أو عُدّل أو جُدول أو نُشر. */
  readonly decided: number
  readonly drafts: number
}

export interface Onboarding {
  readonly steps: readonly Step[]
  readonly done: number
  /** **وتختفي حين تتمّ الخمس** — لا حين يضغط المالكُ «أخفِ». */
  readonly hidden: boolean
  /** أوّلُ خطوةٍ لم تتمّ — وهي الوحيدةُ التي يُطلَب فعلُها الآن. */
  readonly next: Step | null
}

const NONE = 'لم يقع بعد'

/**
 * يشتقّ الخطوات.
 *
 * **والترتيبُ ليس ذوقا**: لا تُكتب مسوّدةٌ بلا تحليل، ولا يُحلَّل بلا
 * مصدر، ولا يُنشَر بلا قناة. **فكلُّ خطوةٍ تفتح التي بعدها**، وعرضُها
 * جميعا قابلةً للفعل يُرسل المالكَ إلى بابٍ مغلق.
 */
export function onboarding(f: OnboardFacts): Onboarding {
  const steps: Step[] = [
    {
      id: 'drive',
      title: 'اربط Drive',
      why: 'بلا مجلّدٍ يُقرأ لا مادّةَ تُكتب منها — والنظامُ يبقى دائرا على فراغ',
      go: '#sources',
      done: f.sources > 0,
      // **والدليلُ مصدرٌ وُجد، لا معرّفُ مجلّدٍ كُتب** (D-061)
      proof: f.sources > 0
        ? `${f.sources} ملفّا قُرئ من المجلّد`
        : 'لا ملفَّ قُرئ بعد — ومعرّفُ المجلّد وحدَه ليس اتّصالا',
    },
    {
      id: 'channel',
      title: 'اربط قناةً واحدة',
      why: 'المسوّدةُ بلا قناةٍ لا تُجدوَل ولا تُنشَر — تبقى نصّا في لوحة',
      go: '#channels',
      done: f.liveAccounts > 0,
      proof: f.liveAccounts > 0 ? `${f.liveAccounts} حسابا حيّا` : NONE,
    },
    {
      id: 'scan',
      title: 'حلّل مصدرا',
      why: 'الكتابةُ تنطلق من خلاصةِ تحليلٍ لا من المستند نفسه',
      go: '#sources',
      done: f.analyzed > 0,
      proof: f.analyzed > 0
        ? `${f.analyzed} من ${f.sources} حُلّل`
        : f.sources > 0 ? `${f.sources} ملفّا ينتظر تحليلا` : NONE,
    },
    {
      id: 'plan',
      title: 'ولّد خطّةَ الأسبوع',
      why: 'الخطّةُ توزّع الجهدَ على الأسبوع — وبلاها يُكتب ما حضر لا ما يلزم',
      go: '#posts',
      done: f.hasPlan,
      proof: f.hasPlan ? 'خطّةٌ محفوظة' : NONE,
    },
    {
      id: 'decide',
      title: 'ابتّ في أوّل مسوّدة',
      why: 'لا يُنشَر شيءٌ بلا قرارك — والقرارُ الأوّل هو الذي يُثبت ذلك',
      go: '#posts',
      done: f.decided > 0,
      proof: f.decided > 0
        ? `${f.decided} مسوّدةً بُتَّ فيها`
        : f.drafts > 0 ? `${f.drafts} مسوّدةً تنتظر قرارك` : NONE,
    },
  ]

  const done = steps.filter((s) => s.done).length
  return {
    steps,
    done,
    hidden: done === steps.length,
    /*
     * **وواحدةٌ تُطلَب لا خمس.**
     *
     * قائمةٌ بخمسةِ أفعالٍ في شاشةٍ أوّلَ مرّةٍ تُقرأ عبئا، **وأوّلُ ما
     * يُفعَل واحد**. والباقياتُ تُعرَض حالا لا دعوة.
     *
     * **وأوّلُ ما لم يتمّ لا أوّلُ ما في القائمة**: من أتمّ الأولى
     * والثالثةَ يُطلَب منه الثانيةُ — لا الأولى التي أتمّها.
     */
    next: steps.find((s) => !s.done) ?? null,
  }
}
