import { describe, expect, it } from 'vitest'
import { nonPublicHost } from './ipGuard'

describe('nonPublicHost — عنوانٌ لا يُنادى في أيّ كتابة (D-318)', () => {
  it.each([
    // ‏الحلقةُ والخاصّةُ والمحلّيّةُ الرابطةُ والمحجوزة — بالنقطيّة
    '127.0.0.1', '10.1.2.3', '172.16.0.1', '172.31.255.255', '192.168.1.1', '169.254.169.254', '0.0.0.0', '100.64.0.1',
    '192.0.0.8', '192.0.2.1', '198.18.0.1', '198.51.100.7', '203.0.113.5', '224.0.0.1', '240.0.0.1', '255.255.255.255',
    // ‏وبكلّ كتابةٍ يقبلها محلّلُ inet_aton: عشريّةٌ واحدة، وثُمانيّة، وستّ عشريّة، ومختصرة
    '2130706433', '017700000001', '0x7f000001', '0x7f.1', '0177.0.0.1', '127.1', '10.1', '0xa9.0xfe.0xa9.0xfe', '0251.0376.0251.0376',
    // ‏وIPv6: الحلقة، وغير المحدَّد، والمحلّيّة، والخاصّة، والمتعدّدة، والتوثيق، و«مُعيَّنةُ IPv4» بكلّ كتابة
    '[::1]', '::1', '[::]', '[fe80::1]', '[fc00::1]', '[fd12:3456::1]', '[ff02::1]', '[2001:db8::1]', '[fec0::1]',
    '[::ffff:7f00:1]', '[::ffff:127.0.0.1]', '[0:0:0:0:0:ffff:7f00:1]', '[::ffff:8.8.8.8]', '[::7f00:1]', '[64:ff9b::a00:1]',
    '[2002:7f00:1::]', '[2001::1]', '[100::1]',
    // ‏والأسماءُ المحلّيّة
    'localhost', 'LOCALHOST', 'printer.local', 'db.internal', 'metadata', 'a.localhost',
  ])('يُردّ: %s', (host) => {
    expect(nonPublicHost(host)).not.toBeNull()
  })

  it.each(['example.com', '8.8.8.8', '1.1.1.1', '172.32.0.1', '[2606:4700:4700::1111]', 'api.deepseek.com', '203.0.114.1'])(
    'يمرّ: %s',
    (host) => {
      expect(nonPublicHost(host)).toBeNull()
    },
  )

  it.each([
    // ‏وما ليس في 2000::/3 (عنوانُ الإنترنت الوحيد في IPv6) لا يُنادى: المترجَمةُ (::ffff:0:0:0/96) وNAT64 المحلّيّة
    // ‏(64:ff9b:1::/48) وكلُّ ::/8 المحجوزة، ثمّ ما حُجز داخل 2000::/3 نفسِها: بروتوكولاتُ IETF (2001::/23)، والتوثيقُ
    // ‏الجديد (3fff::/20)، ومعرّفاتُ SRv6 (5f00::/16)
    '[::ffff:0:7f00:1]', '[::ffff:0:127.0.0.1]', '[64:ff9b:1::a00:1]', '[::2:1]', '[1::1]', '[400::1]', '[2001:10::1]',
    '[2001:1ff::1]', '[3fff::1]', '[5f00::1]', '[8000::1]', '[e000::1]',
  ])('ويُردّ خارج نطاق الإنترنت في IPv6: %s', (host) => {
    expect(nonPublicHost(host)).not.toBeNull()
  })

  it.each(['[2a00:1450:4001::200e]', '[2001:4860:4860::8888]', '[2400:cb00::1]', '[2002:808:808::1]'])(
    'ويمرّ عنوانُ إنترنتٍ في IPv6: %s',
    (host) => {
      expect(nonPublicHost(host)).toBeNull()
    },
  )

  it('وما يطبّعه محلّلُ العناوين يُفحص بعد التطبيع كما قبله', () => {
    for (const raw of ['https://0x7f.1/', 'https://2130706433/', 'https://[::ffff:127.0.0.1]/', 'https://0251.0376.0251.0376/']) {
      expect(nonPublicHost(new URL(raw).hostname), raw).not.toBeNull()
    }
  })
})
