/**
 * خليّةُ CSV لا تصير صيغة (D-318).
 *
 * جدولُ البيانات ينفّذ خليّةً تبدأ بـ`=` أو `+` أو `-` أو `@` — وبالجدولة
 * (`\t`) أو رجوعِ السطر (`\r`) أيضًا، لأنّ بعض البرامج تُسقطهما ثمّ تقرأ ما
 * بعدهما صيغة. **ونصُّ المنشور يكتبه غيرُنا** (عميلٌ، أو نموذجٌ، أو مصدرٌ
 * مقروء)، فـ`=HYPERLINK("https://…","اضغط")` في منشورٍ يصير رابطًا في ملفّ
 * المالك يفتحه Excel.
 *
 * والعلاجُ ما توصي به OWASP: **فاصلةٌ عليا قبل الخليّة** فتُقرأ نصًّا. وكان
 * `pivot.ts` يفعلها بلا الجدولة ورجوع السطر، وملفُّ «ما ينجح» لا يفعلها
 * أصلًا — فصارت دالّةً واحدة يقرؤها الملفّان.
 */
export function neutralizeFormula(raw: string): string {
  return /^[=+\-@\t\r]/.test(raw) ? `'${raw}` : raw
}
