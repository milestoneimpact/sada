/**
 * قراءةُ سببِ الرفض — **والمنصّةُ تسمّي النطاقَ، ونحن أهملناه**.
 *
 * ## العلّةُ التي وُلد منها هذا الملفّ
 *
 * قلتُ في D-045: «المنصّةُ لا تقول أيَّ واحدٍ رفضت، فكلُّها معروضة».
 * **وكان ذلك خطأً**. عادت LinkedIn بهذا في العنوان:
 *
 *     error=unauthorized_scope_error
 *     error_description=Scope "openid" is not authorized for your application
 *
 * فالاسمُ كان هناك، **وصفحةُ التشخيص عرضت ثلاثةً وتقول «لا أعرف أيَّها»**
 * — وهي تعرف. وعرضُ ثلاثةٍ حيث يُعرَف واحدٌ ليس حيطةً، **هو إضاعةُ
 * معلومةٍ وصلت**: المالك يذهب إلى البوّابة يفحص ثلاثةَ منتَجاتٍ وأحدُها
 * وحده الناقص.
 *
 * ## ولا يُوثَق بالنصّ وحده
 *
 * الصياغةُ تتبدّل بلا إعلان — وهذا هو سببُ قاعدةِ «الرمزُ لا النصّ» في
 * كلّ سائقٍ عندنا. فيُستخرَج الاسمُ **ثمّ يُطابَق على سجلٍّ نعرفه**: ما
 * وافق نطاقا مسجَّلا أُخذ، وما لم يوافق أُهمل وعُرضت القائمةُ كاملة.
 *
 * **فالنصُّ يُضيّق ولا يقرّر.** ورسالةٌ تتبدّل تُعيدنا إلى ما كان، ولا
 * تُدخلنا في خطأ.
 */

/**
 * أسماءُ النطاقات المذكورةُ في وصف الخطأ.
 *
 * وتُقبَل صيغتان: `"openid"` كما ترسلها LinkedIn، و `'openid'` — وبعضُ
 * المنصّات يهرّب الاقتباسَ إلى `&quot;` فيصل مفكوكا أو غيرَ مفكوك،
 * فيُقبَل الاثنان.
 */
export function namedScopes(description: string): string[] {
  const found = new Set<string>()
  const patterns = [/"([^"]{2,40})"/g, /&quot;([^&]{2,40})&quot;/g, /'([^']{2,40})'/g]
  for (const pattern of patterns) {
    for (const match of description.matchAll(pattern)) {
      const value = match[1]?.trim()
      // اسمُ نطاقٍ لا جملة: حروفٌ صغيرةٌ ونقاطٌ وشُرَطٌ سفليّة
      if (value !== undefined && /^[a-z0-9_.]+$/.test(value)) found.add(value)
    }
  }
  return [...found]
}

/**
 * أيُّ النطاقات المطلوبة سمّته المنصّةُ بالاسم؟
 *
 * ولا يُؤخَذ إلّا ما كان **في ما طلبناه فعلا**: وصفٌ يذكر نطاقا لا
 * نعرفه إمّا أن يكون تبدّلا في الصياغة أو ذكرا عرَضيّا، **وكلاهما لا
 * يُبنى عليه**.
 */
export function blamedScopes(
  description: string,
  requested: readonly string[],
): string[] {
  const known = new Set(requested)
  return namedScopes(description).filter((name) => known.has(name))
}
