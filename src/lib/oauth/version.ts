/**
 * عمرُ `LinkedIn-Version` المثبَّتة — **ثابتٌ يشيخ بلا أن يقول**.
 *
 * ## لماذا
 *
 * LinkedIn تُصدِر نسخةً شهريّةً (`YYYYMM`)، **وتُسقط القديمةَ بعد
 * مدّة**. والنسخةُ عندنا رقمٌ مكتوبٌ في `providers.ts`، و`PLATFORMS.md`
 * تقول عنه: «**تُرفَع يدوياً بعد قراءة ملاحظات التغيير**».
 *
 * **ومهمّةٌ يدويّةٌ بلا مُذكِّرٍ لا تقع.** فيومَ تسقط النسخةُ يتوقّف
 * النشرُ كلُّه بخطأٍ من المنصّة، **ولا شيءَ في اللوحة كان يقول إنّ
 * الرقمَ شاخ** — وهي علّةُ D-066 بعينها: حارسٌ في تعليقٍ لا في شيفرة.
 *
 * ## وما يُقاس هنا هو عمرُنا لا سياستُهم
 *
 * **لا يُدَّعى هنا كم تدعم LinkedIn نسخةً.** لم أقرأ ذلك من مصدرٍ
 * أتحقّق منه من هذه البيئة، **ورقمٌ يُخترَع أسوأُ من لا رقم** (D-071).
 *
 * فالمقيسُ حقيقةٌ تُحسَب بلا ادّعاء: **كم شهرا مضى على النسخة
 * المثبَّتة**. والعتبةُ أدناه **دورةُ مراجعتنا نحن** — متى يُذكَّر
 * المالكُ أن يقرأ ملاحظاتِ التغيير — لا حدُّ المنصّة. وقراءةُ الحدّ
 * الحقيقيّ **مهمّةُ M-18** نفسُها.
 */

/** بعد كم شهرٍ يُذكَّر المالكُ بمراجعة الرقم — **دورتُنا لا سياستُهم**. */
export const REVIEW_AFTER_MONTHS = 9

export interface VersionAge {
  /** الشهورُ منذ الشهر الذي تسمّيه النسخة. */
  readonly months: number
  /** أبلغَت دورةَ المراجعة؟ */
  readonly due: boolean
}

/**
 * يقرأ `YYYYMM` ويعيد شهورَ عمرِه.
 *
 * **وصيغةٌ لا تُقرأ لا تُعدّ صفرا**: تعيد `null`، فيبقى الحكمُ «لا
 * يُعرَف» ولا يُقال «حديثة» عن رقمٍ لم يُفهَم (D-063).
 */
export function versionAge(version: string, now: Date): VersionAge | null {
  const m = /^(\d{4})(\d{2})$/.exec(version.trim())
  if (m === null) return null
  const year = Number(m[1])
  const month = Number(m[2])
  if (month < 1 || month > 12) return null

  const months =
    (now.getUTCFullYear() - year) * 12 + (now.getUTCMonth() + 1 - month)
  return { months, due: months >= REVIEW_AFTER_MONTHS }
}
