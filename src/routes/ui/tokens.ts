/**
 * رموزُ التصميم — والثيمان من قيَمٍ واحدة.
 *
 * ## لماذا الرموز لا الألوان
 *
 * كلُّ قاعدةٍ في `styles.ts` تكتب `var(--…)` ولا تكتب لونا. فالثيمُ
 * يُقلَب بإعادة تعريف القيَم هنا وحدها — لا بنسخِ ورقةِ أنماطٍ ثانية
 * تتباعد عن الأولى مع كلّ تعديل. **وبهذا وحدَه بُدّلت الهويّةُ ثالثةً بلا قاعدةٍ تُكتب.**
 *
 * ## أسطحٌ محايدةٌ وتركوازٌ يُضغط وعمقٌ يُبنى (D-246، على هويّة D-196)
 *
 * أرسل المالكُ لوحةَ الهويّة الرسميّة (D-196): تسعةُ ألوان، وشعارٌ شريطٌ حريريّ، وحريرٌ وخيوطُ ذهبٍ على أخضرَ
 * فيروزيٍّ عميق. **ثمّ اعتمد تصميمًا للّوحة اليوميّة (D-246)** بدّل الرملَ الدافئ بأسطحٍ محايدة: فالهويّةُ في العلامة
 * ولحظاتها (`MARK` و`MOMENT`)، وفي الزرّ والرابط، وفي العمق الذي يحمل البنية — **وبقي الانضباطُ من D-144 وD-187**:
 * أسطحٌ هادئة، والحبرُ لونُ البنية، ومعدنٌ واحدٌ يُقتَّر، وألوانُ الحال وحدَها مشبعة.
 *
 * **نهارًا ورقٌ محايد**: الأرضُ رماديّةٌ فاتحةٌ تكاد تبيضّ (‏#f6f7f8)، والبطاقةُ بيضاء، والسطحان الداخليّان درجتان
 * محايدتان، والحبرُ رماديّاتُ Tailwind الثلاثة (‏#111827 و‏#374151 و‏#4b5563) — بهيولاها الزرقاء، فلا رملَ تنازعه بعد
 * اليوم. **والزرُّ الأوّليُّ والرابطُ تركوازٌ واحد** (‏#0e6b64): لونُ ما يُضغط، والرابطُ مسطَّرٌ دائمًا. **و«--accent» عمقُ
 * اللوحة** (‏#0b2f31): ما يُبرز ولا يُضغط — مِلءُ المقياس، وحافّةُ المؤشّر، وحلقةُ اليوم، وحدُّ المختار (D-325).
 *
 * **ليلًا أرضٌ تكاد تسودّ** (‏#0b0f14) بسطوحٍ رماديّةٍ زرقاء ثلاث، **والزرُّ الأوّليُّ تركوازٌ فاتحٌ جدًّا** (‏#e3f1ef)
 * بحبرٍ عميق — أسطعُ ما في الشاشة — والرابطُ نعناعٌ مكتوم (‏#a9dbd4)، و«--accent» الفاتحُ نفسُه: بُعدُه عن الرابط يحرسه
 * `validate_contrast` في الوضعين، فالتركوازُ لا يُقرأ «يُضغط» حيث لا يُضغط.
 *
 * ### والنعناعُ ضوءٌ على عمق — لا تعبئةٌ ولا نصٌّ على فاتح
 *
 * نعناعُ اللوحة ‏#4cd1b6 **هو القياسُ نفسُه** الذي قال عنه المالكُ «قاسٍ وليس بقوّة» (D-053،
 * والتاريخُ أدناه). **واللوحةُ تنجح به لأنّها لا تضعه مصمتًا على فاتح**: على الرمليّ والأبيض
 * يقع داخل تدرّجٍ يحمل التركوازَ والعمق (الشعارُ الأساسيّ والقفلان وأيقونةُ التطبيق الفاتحة)،
 * ومصمتًا على العمق وحده (الغلافُ والأيقونةُ الداكنة). ولا تدرّجَ في الواجهة (خطّة التصميم 3.1)،
 * فهو هنا بقيمته في موضعٍ واحد — **شريطُ العلامة على أرضها** (`MARK`) —
 * وفي لحظات العلامة (`MOMENT`)، **ومكتومًا** في رابط الليل. ولا يصير زرًّا ولا محدَّدًا ولا
 * نصًّا على فاتح: **وتلك هي تجربةُ D-049 التي رُدّت**. ويحرس `validate_contrast` إشباعَ أسرته كلِّها في الوضعين.
 *
 * ### والذهبُ خلَف النحاس: الأدوارُ الثلاثة نفسُها
 *
 * «الذهبيّ الهادئ» ‏#c9a96a على الأبيض ‏٢٫٢٤:١ — يختفي. **فنهارًا يُعتَم على هيولاه وإشباعه
 * إلى برونز**، وليلًا هو ذهبُ اللوحة بقيمته. **ذهبان لا ثلاثة**: خيطُ لحظة العلامة يقرأ ذهبَ
 * الليل لا ثالثًا. وقاعدةُ D-187 كما هي: **ثلاثةُ مواضعَ في الشاشة لا رابعَ لها** — العلامةُ،
 * ومؤشّرُ القسم الحاليّ، والرقمُ البطل — يعدّها `audit_design` في كلّ شاشةٍ مرسومة.
 *
 * ### وألوانُ الحال ليست الهويّة
 *
 * كان «الجيّد» في D-196 أخضرَ غابٍ مائلًا عن التركواز، **وأعاده D-246 زمرّدًا** (‏#065f46، Tailwind): بُعدُه عن
 * الرابط ΔE_OK ‏5.4 نهارًا — يُطبَع ولا يُردّ — فلا يُقرأ حالًا بلونه وحدَه. **وكلُّ حالٍ رمزٌ وكلمةٌ معًا**، ونقاطُ
 * الرافدة الثلاثُ تتمايز عند من لا يميّز الأحمرَ من الأخضر بفحصٍ يردّ.
 *
 * ### والأرقامُ هناك لا هنا
 *
 * الأزواجُ تُقاس في النهاريّ والداكن والطباعة بـ`scripts/validate_contrast.js`: نسبةُ WCAG،
 * وAPCA Lc لما يحمل المعنى، وΔE_OK للتمايز، وعمى الألوان الثلاثة. **والأرقامُ هناك لا هنا** —
 * رقمٌ يُنسَخ إلى شرحٍ يشيخ عند أوّل تعديل. **وقيمتان مجمَّدتان** لأنّهما أرقُّ الأزواج: أرضُ
 * النهار (التحذيرُ عليها على الحدّ، وحبّةُ التحذير على أرضها كذلك) وتحذيرُ الليل (حبّتُه على الحدّ
 * وبعدُه عن الذهب). من يُعتم الأرضَ، أو يُميل التحذيرَ نحو الذهب، يُسقط الفحص — **ويثبّتهما `views.test`**.
 * **والوثائقُ لا تنسخ قيمةً إلّا وهي هنا**: `npm run docs` يردّ كلَّ لونٍ في `BRAND.md` وخطّة التصميم ليس من
 * هذا الملفّ ولم يُعلَّم تاريخًا (D-325) — وكانت الوثيقتان تصفان لوحةَ D-196 بعد أن بدّلتها D-246.
 *
 * ## ما قبلها: لماذا كان الأخضرُ قاسيا — وما الذي قيس (تاريخ)
 *
 * قيل إنّ اللون «قاسٍ وليس بقوّة». **وكان محقّا، وقياسُ OKLCH يقوله
 * بالأرقام**:
 *
 *   النعناع الذي كان   L 78.1 · C 0.122 · H 177°
 *   فيروزٌ صارخ        L 82.2 · C 0.131 · H 185°
 *   أخضرُ سباقٍ بريطانيّ L 33.4 · C 0.079 · H 157°
 *
 * **فالذي كان يقع في أسرة الفيروز الصارخ لا في أسرة الأخضر الفخم**:
 * القياسات الثلاثة متقاربة. وثلاثةُ فروقٍ تصنع «الفخم»:
 *
 * ١ · **الهيولى.** ‏١٧٧° سماويٌّ يُقرأ طبّيّا وتقنيّا. والزمرّدُ عند
 *     ‏١٥٥–١٦٥° يُقرأ حجرا كريما. **ودورانُ الهيولى نحو ١٥٨° هو عينُ
 *     ما يعنيه «أكثِر الأخضرَ بالذهبيّ»** — فالدورانُ نحو الأصفر.
 *
 * ٢ · **الإشباع عند الفاتح.** لونٌ فاتحٌ عالي الإشباع يُقرأ **نيونا**.
 *     فأُنزل من ‏٠٫١٢٢ إلى ‏٠٫٠٩٠ — والفخامةُ في الكِتمان لا في الصراخ.
 *
 * ٣ · **التباينُ من عمق الأرض لا من سطوع اللون.** فأُعمقت الأرضُ
 *     ودارت هيولاها معه، فصار الحيّزُ كلُّه زمرّدا لا سماويّا.
 *
 * **والفرقُ الثالث هو ما تفعله اللوحة** (D-196): الأرضُ العميقة تصنع الفخامة، والنعناعُ ضوءٌ
 * عليها. **والفرقُ الثاني حدٌّ مكتوب**: رابطُ الليل مكتومٌ تحت ‏٠٫٠٩٠.
 *
 * ## لكلّ لونٍ وظيفةٌ واحدة (خطّة التصميم 3.2 · D-196)
 *
 * `--brand` تعبئةُ الزرّ الأوّليّ وحدَها (والزرُّ العائم ورابطُ التخطّي، وهما زرّان أوّليّان). و`--link` حبرُ
 * الرابط والزرّ الهادئ وحلقةِ التركيز (`--focus`). **و`--accent` ما يُبرز ولا يُضغط** (D-325): مِلءُ المقياس والرسم،
 * وحافّةُ المؤشّر، وحلقةُ اليوم، وحدُّ المختار وعلامتُه — وكانت كلُّها `--brand`، ونهارًا `--brand` و`--link` قيمةٌ واحدة،
 * فـ«التركوازُ يُضغط» لم يعد يصدق. ويحرس `roles.test` أنّ `--brand` في الزرّ الأوّليّ وحده، و`--pf-*` في الشعار وحده.
 * و`--field` حدُّ ما يُكتب فيه ويُضغط (‏3:1، WCAG 1.4.11)، و`--line`
 * حدُّ البطاقة زينةً يسندها الظلّ. و`--au` **تشديدٌ ونُدرة**: لا حدَّ بطاقةٍ ولا خطَّ
 * رابطٍ ولا شريطَ رسمٍ ولا حالَ ولا وهج — **وذهبٌ يُملأ به سطحٌ يُقرأ رخيصا**.
 * ويعدّ مواضعَه `audit_design` في كلّ شاشةٍ مرسومة، و`audit_tokens` في الورقة.
 * والتفصيلُ كلُّه — النِّسَبُ واللحظاتُ والشعارُ والصور — في `docs/BRAND.md`.
 */

