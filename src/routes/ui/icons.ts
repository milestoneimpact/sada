/**
 * الأيقونات — **مصدرٌ واحدٌ ومواصفةٌ تُفرَض، لا رسمٌ يُعاد** (D-103).
 *
 * ## ما وُجد عند القياس
 *
 * قالت الخطّةُ إنّ الأيقونات «خليطُ `fill` و`stroke` بلا شبكةٍ موحّدة»،
 * **فقِيست فوُجدت أقربَ إلى نظامٍ ممّا قيل**: تسعٌ من إحدى عشرةَ على
 * شبكة ‏٢٤ وثخانة ‏١٫٨ و`currentColor`.
 *
 * **فالناقصُ لم يكن رسما — كان مصدرا واحدا وحارسا.** وكنّ موزّعاتٍ على
 * ثلاثة ملفّات، فمن يضيف أيقونةً غدا ينسخ أقربَ ما يجده، **وما نُسخ عن
 * مخالفٍ خالف**.
 *
 * ## والمواصفةُ تُفرَض بالبناء لا بالمراجعة
 *
 * لا تُكتب `svg` هنا بيد: تُكتب أشكالُها وحدَها، ويلبسها `icon()`
 * المواصفةَ. **فأيقونةٌ تخالف لا تُكتب أصلا** — وهي أقوى من مدقّقٍ يمسك
 * المخالفَ بعد كتابته.
 *
 * ## وشعاراتُ المنصّات ليست من هذا
 *
 * `LOGOS` علاماتٌ مسجّلةٌ لأصحابها: تُرسَم `fill` بمساراتها كما نشروها،
 * **وتوحيدُها على مواصفتنا تشويهٌ لعلامةِ غيرِنا**. فتبقى حيث هي.
 */
