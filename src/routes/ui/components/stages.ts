/**
 * **مراحلُ الانتظار الطويل** (خطّة التصميم 7.11 · D-237).
 *
 * الكتابةُ والصورةُ والمقطعُ نداءٌ واحدٌ إلى مزوّدٍ يطول عشرَ ثوانٍ أو أكثر، والزرُّ «جارٍ…» ساكنٌ طولَها،
 * فلا يدري المالكُ أيعمل شيءٌ أم علق. فالنموذجُ يحمل `data-stages` بمراحلَ مسمّاة، **وسكربتُ «مشغول»
 * يقلّبها بالوقت** في سطر الانتظار: ليست تقدّمًا من الخادم، فلا رقمَ ولا نسبة، **وتقف عند آخرها** فلا
 * تقول «جاهزة» قبل الردّ. وبعد عشر ثوانٍ يُضاف «ابقَ في الصفحة»: الطلبُ في هذه الصفحة، ومغادرتُها تقطعه.
 */
const join = (s: readonly string[]): string => s.join('|')

export const STAGES = {
  write: join(['يقرأ خلاصةَ المصدر…', 'يكتب المسوّدة…', 'يراجع الطولَ وقواعدَ المنصّة…']),
  idea: join(['يقرأ فكرتك…', 'يكتب لكلّ منصّةٍ مسوّدتَها…', 'يراجع الطولَ وقواعدَ المنصّة…']),
  image: join(['يقرأ المنشور…', 'يرسم الصورة…', 'يحفظها مع المسوّدة…']),
  motion: join(['يرسل الصورةَ إلى خدمة الفيديو…', 'يحرّكها…', 'يحفظ المقطع…']),
  captions: join(['يقرأ المقطع…', 'يكتب النصوص…']),
} as const

/** سمةُ النموذج: `data-stages="…"`. */
export function stagesAttr(kind: keyof typeof STAGES): string {
  return `data-stages="${STAGES[kind]}"`
}
