/**
 * الحالُ والعدد — **شارتان لا ثمانٍ** (خطّة التصميم 7.2 · D-189).
 *
 * كانت الحالُ تُقال بنحو خمسَ عشرةَ طريقة: حبّةٌ، ورقاقةٌ، وسطرُ «بلغ السقف»، وسهمُ
 * الفرق، ووسمٌ على المسرح، ولصيقةُ «إن نجح». **وما تتعلّمه في شاشةٍ لا تعرفه في
 * أخرى.** فصارت شارتين: `statusBadge` للحال (لونٌ ورمزٌ وكلمةٌ معًا، D-043) و`count`
 * للعدد. وكلٌّ صنفٌ واحدٌ في الورقة: «.st» و«.count».
 */
import { escapeHtml } from '../escape'
import { glyph } from '../icons'

/** النغماتُ الخمس — والمحايدان يفترقان بالرمز لا باللون: ينتظر ساعة، ولم يبدأ دائرةٌ متقطّعة. */
export type Tone = 'ok' | 'warn' | 'bad' | 'pending' | 'idle'

/**
 * شارةُ الحال — **دالّةٌ واحدةٌ ورموزٌ مرسومة** (D-154 · نُقلت من `parts.ts` في D-189).
 *
 * كانت الشارةُ تُكتب يدًا (حبّةٌ ورمزٌ بصنف «g» وحرفٌ من خطّ النظام) ‏٦٥ مرّةً في
 * عشرة ملفّات، ورمزُها حرفٌ ليس في أيّ وجهٍ مضمَّن. هنا يُرسَم SVG بـ`currentColor` من
 * `icon()` (شبكةُ ‏٢٤ وثخانةُ ‏١٫٨، ‏١٤px في الشارة)، **والحرفُ يبقى مفتاحَه** في جداول الحال.
 *
 * `tone` من النغمات الخمس (أو فارغ)، و`g` حرفُ الحال، و`text` وسمٌ جاهزٌ (مهرَّبٌ عند
 * من كتبه)، و`attrs` سِماتٌ تُلحَق بالشارة. **وصنفُ الرمز «st-ic» لا «g»** (D-183):
 * «.g» كان صنفَ الزرّ الثانويّ، فلبس الرمزُ أرضَه البيضاءَ داخل كلّ حبّةٍ ملوّنة.
 */
export function statusBadge(tone: Tone | '', g: string, text: string, attrs = ''): string {
  const open = `<span class="st${tone === '' ? '' : ` ${tone}`}"${attrs === '' ? '' : ` ${attrs}`}>`
  return `${open}<span class="st-ic">${glyph(g)}</span>${text}</span>`
}

export interface CountInput {
  /** «bad» حين يعني العددُ شيئًا فشل؛ والمحايدُ ما سواه. */
  readonly tone?: 'bad'
  /** نصٌّ لقارئ الشاشة حين لا يكفي الرقمُ وحدَه («٣ تنتظرك»). */
  readonly label?: string
}

/**
 * العدد — **رقمٌ ‏١٣px بوزن ‏٦٠٠ على «--surface-3»** (خطّة التصميم 7.2).
 *
 * يجاور التبويبَ وعنصرَ الرافدة، **ويعني «ينتظرك» وحدَها** (5.1): عددُ ما في القائمة
 * لا يُعلَّق على كلّ باب. والفاشلُ بنغمته، فلا يُقرأ عددًا كسائره — و«!» عددُ ما لا يُعَدّ:
 * إعدادٌ سقط في تبويب «الإعداد»، ومعه نغمتُه.
 */
export function count(n: number | '!', input: CountInput = {}): string {
  const tone = input.tone === undefined ? '' : ` ${input.tone}`
  const label = input.label === undefined ? '' : ` aria-label="${escapeHtml(input.label)}"`
  return `<span class="count${tone}"${label}>${n}</span>`
}
