/**
 * تهريبُ النصّ — **وحدةٌ بلا استيراد** (D-160).
 *
 * كانت في `shell.ts`، فكلُّ لوحٍ يهرّب نصًّا استورد القشرة، والقشرةُ تستورد
 * الأصلَ، والأصلُ يستورد سكربتَ اللوحة، واللوحةُ تستورد الألواح: حلقةٌ من
 * ثلاث عشرة وحدة. وفي الحلقة يقرّر esbuild ترتيبًا غيرَ ترتيب الاختبار، فيُقرأ
 * ثابتٌ قبل أن يُسنَد ويُطبَع «undefined» في رأس سكربتٍ لا يعمل بعدها.
 *
 * **وورقةُ الرسم لا تستورد شيئًا**: ما لا يستورد لا يدخل حلقة.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;')
}
