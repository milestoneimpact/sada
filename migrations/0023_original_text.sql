-- ما تغيّر قبل الاعتماد — **الأصلُ يُحفَظ عند أوّل تعديل** (D-128).
--
-- `status = 'edited'` تقول إنّ المالكَ عدّل النصَّ قبل أن يعتمده،
-- **ولا تقول ما الذي عدّله**: النصُّ الأصليُّ الذي كتبه النموذجُ يُدهَس
-- بالمعدَّل، ويبقى في الدفتر ثمنُه ولا يبقى هو. ومالكٌ يراجع بعد أسبوع
-- «لماذا عُدّلت هذه» لا يجد جوابا.
--
-- فعمودٌ يحفظ الأصلَ **مرّةً واحدة**: يُكتب عند أوّل تعديلٍ من النصّ الذي
-- كان، ولا يُكتب ثانيةً (`COALESCE` في الشيفرة). و`NULL` تعني «لم يُعدَّل»
-- لا «لا أصلَ له» — فمسوّدةٌ اعتُمدت كما كُتبت أصلُها نصُّها.
--
