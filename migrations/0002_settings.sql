--
-- تُحفظ في D1 لا في KV: قيمةٌ تحكم الإنفاق تُقرأ في مراجعة، وتُنسخ مع
-- القاعدة، وتُستعاد معها. و KV يصلح لجلسةٍ تنتهي، لا لقرارٍ يُحاسَب عليه.
--
-- والقيم نصوص مهما كان نوعها المنطقيّ: عمودٌ واحد يقبل ما يجيء لاحقا بلا
-- ترحيلٍ جديد، والتحقّق من النوع يقع في الشيفرة حيث يُختبَر.

CREATE TABLE settings (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL DEFAULT (datetime('now')),
  -- مَن غيّرها: 'panel' أو 'seed' أو 'api'. أثرٌ قابل للتدقيق (D-024)
  updated_by TEXT
);

-- القيم الأولى. `INSERT` لا `INSERT OR REPLACE`: ترحيلٌ يُعاد تطبيقه
-- لا يدهس سقفا رفعه المالك بيده.
