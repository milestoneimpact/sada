-- ── قناةُ الإخراج للتنبيهات (D-109) ─────────────────────────────────
-- `token_alerts` (0016) يسجّل أنّ رمزا يقترب، **ولا قناةَ إخراجٍ له**:
-- يُكتَب الصفُّ ولا يعلم به أحدٌ حتّى يدخل المالكُ اللوحة. **وما لا
-- يُكتشَف إلّا بالدخول ليس تنبيها.**
--
-- وهذا الجدولُ يسجّل **ما خرج**، لا ما وقع. والفرقُ بينهما هو الفرقُ
-- بين `token_alerts` وهذا: الأوّلُ حدثٌ، والثاني إرسالُه.
--
-- **ولا يُرسَل حدثٌ مرّتين** (D-004): `ref` مفتاحٌ يُبنى من الحدث نفسِه
-- — لا من وقت الإرسال. فدورةٌ تُعاد بعد فشلٍ في الشبكة لا تُغرِق قناةَ
-- المالك بما رآه.
CREATE TABLE alert_outbox (
  -- مفتاحُ الحدث: نوعُه ومرجعُه وعتبتُه. ومكرَّرٌ يُردّ بالقيد لا بالشيفرة
  ref        TEXT PRIMARY KEY,
  kind       TEXT NOT NULL CHECK (kind IN ('token', 'publish', 'budget')),
  -- ما قيل، بلا سرٍّ ولا رمزٍ ولا رابطٍ موقَّع (CLAUDE.md · D-005)
  body       TEXT NOT NULL,
  -- ‏٢٠٠ أو رمزُ الخطأ. و`null` أنّ النداءَ لم يعد بجواب
  status     INTEGER,
  -- سببٌ يُقرأ حين يفشل — لا «تعذّر الإرسال»
  error      TEXT,
  at         TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX idx_alert_outbox_at ON alert_outbox (at);
