--
-- ## لماذا
--
-- كان `plan_json.items[].day/time` بتوقيتين: المعالجُ والاستيرادُ والإضافةُ يحفظونه بـ UTC، و`slotFor` والفحصُ
-- و`moveItem` يقرؤونه بتوقيت المالك (D-383). فخرج منشورُ 09:00 الرياض في 03:00Z (تحويلٌ مرّتين)، وقال الفحصُ
-- «06:00 داخل ساعات الهدوء». والاتّفاقُ الواحد الآن: **البندُ بتوقيت المالك** في كلّ مكان.
--
-- ## ما يُضاف
--
-- - `plans.time_basis`: افتراضُه `local` لكلّ ما يُكتب بعد هذا الترحيل، و**كلُّ صفٍّ قائمٍ يُختم `utc`** بالتحديث أدناه
--   (كُتب قبل الإصلاح، فبنودُه بـ UTC — إلّا ما نقله «أزِح» بعد D-383، وهو قليلٌ ويُزاح ثانيةً إن لزم). والقارئُ (`localizePlan`) يحوّل خطّةَ `utc` إلى توقيت المالك **مرّةً واحدة** عند أوّل لمسة، بتحديثٍ مشروط
--   `WHERE time_basis = 'utc'` فلا يُحوَّل بندٌ مرّتين ولو تسابق طلبان.
--
-- لا يُحذف صفٌّ ولا يتغيّر عمودٌ قائم. والمنشوراتُ المجدولةُ خطأً قبل الإصلاح لا يمسّها هذا الترحيل؛
-- تصحيحُها يدويٌّ موثَّقٌ في docs/RUNBOOK.md «D-384».

ALTER TABLE plans ADD COLUMN time_basis TEXT NOT NULL DEFAULT 'local';
UPDATE plans SET time_basis = 'utc';
