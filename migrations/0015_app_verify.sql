-- أثرُ الفحص — **لأنّ نتيجةً تُنسى عند كلّ فتحةٍ ليست نتيجة.**
--
-- D-060 بنى فحصَ زوج الأسرار. وكان جوابُه إشعارا يمرّ ويزول، **فيعود
-- المعالجُ في الفتحة التالية لا يعرف شيئا** — ويُسأل المالكُ أن يفحص
-- مرّةً بعد مرّة.
--
-- ## ولماذا صفٌّ لا حسابٌ عند العرض
--
-- الفحصُ **نداءٌ خارجيّ**. وحسابُه عند كلّ فتحةِ لوحةٍ يعني نداءً إلى
-- المنصّة في كلّ مرّة — **بطءٌ، وحدُّ نداءاتٍ يُستهلك بلا سبب**، وحالٌ
-- تتبدّل تحت عين المالك بلا فعلٍ منه.
--
-- فيُحفَظ ما وقع بوقته، **ويُبطَل حين يُبدَّل السرّ**: نتيجةٌ عن سرٍّ
-- مضى أسوأُ من لا نتيجة — تقول «مفحوص» عن شيءٍ لم يُفحَص.

ALTER TABLE oauth_apps ADD COLUMN verified_at   TEXT;
