-- ومعنيان في قيمةٍ واحدة يجعلان دورة Cron الثانية ترسل ما أرسلته الأولى.
-- و `idempotency_key` يمنع النشرَ مرّتين (D-004) — **لكنّه لا يمنع
-- استنزافَ حصّة الطابور**: الرسالةُ تدخل وتُقرأ وتُقَرّ، وثمنُها مدفوع.
--
-- فعمودٌ يفصل بينهما: بلا خَتمٍ ينتظر، وبه أُرسل.
