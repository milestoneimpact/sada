-- نبضُ التشغيل — **هل دارت الدورةُ فعلًا، ومتى، وبماذا خرجت؟** (D-158).
--
-- كلُّ دورةٍ (`renew` و`dispatch` و`scan` و`alerts` و`metrics` و`report`)
-- وكلُّ دفعةِ نشرٍ من الطابور كانت تكتب في `console` وحده، **ولا صفَّ في
-- القاعدة يقول إنّها وقعت**. فمالكٌ يرى منشورًا مجدولًا فات موعدُه لا يعرف:
-- أدارت الدورةُ فلم تجد ما تُرسل، أم لم تدُر أصلًا (دقائقُ نفدت، أو نشرٌ
-- سقط، أو cron مُطفأ)؟ وجدولُ `publish_attempts` وحدَه يشهد على الطابور،
-- ولا يشهد على دورةٍ لم تجد شيئًا.
--
-- صفٌّ واحدٌ لكلّ دورة يُستبدَل عند كلّ نبضة: **الأحدثُ لا السجلّ كلُّه**،
-- فالسؤالُ «متى آخرُ مرّة» لا «كم مرّة». والسجلُّ الكاملُ في Cloudflare.
-- **والترحيلُ قبل الدالّة** (CLAUDE.md).
CREATE TABLE heartbeats (
  job TEXT PRIMARY KEY,
  at TEXT NOT NULL DEFAULT (datetime('now')),
  -- 'ok' · 'failed' · 'skipped'
  outcome TEXT NOT NULL CHECK (outcome IN ('ok', 'failed', 'skipped')),
  detail TEXT
);
