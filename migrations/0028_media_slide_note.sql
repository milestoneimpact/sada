-- ما قيل عن الشريحة يبقى مع الصورة — **لا في الوميض وحدَه** (D-157 · D-162).
--
-- `noteOf` تقول لماذا لم يُركَّب النصُّ فوق الصورة، والموجزُ البصريُّ يعطي
-- العنوانَ العربيّ. وكلاهما كان يُقال مرّةً في الوميض ثمّ يُرمى: البطاقةُ
-- بعد أوّل تحديثٍ لا تعرف أرُكّب النصُّ أم سقط، ولا ما الذي رُكّب — فيعتمد
-- المالكُ صورةً بلا عنوانٍ وهو لا يدري، أو يرفضها ويدفع ثمنَ توليدٍ ثانٍ
-- على أملِ أن يظهر النصّ.
--
-- و`note` **ثلاثيّةُ القيمة**، والفرقُ بينها هو الخبر:
--   NULL — صفٌّ أقدمُ من هذا الترحيل، أو مقطعٌ لا شريحةَ له: **لم يُسجَّل**
--   ''   — رُكّب النصّ
--   نصٌّ — سببُ السقوط كما قيل يومَ التوليد
-- و`headline` هو ما رُسم أو كان سيُرسَم، و**NULL حين لا عنوانَ في الموجز**
-- — ولا يُخترَع.
--
-- وأمران لا أمرٌ واحد: SQLite لا يقبل عمودين في `ALTER` واحد.
-- **والترحيلُ قبل الدالّة** (CLAUDE.md): `INSERT` بأحدَ عشرَ عمودًا على
-- قاعدةٍ لم تأخذ هذا الملفَّ يسقط **بعد** أن دُفع ثمنُ الصورة.
ALTER TABLE media ADD COLUMN note TEXT;
ALTER TABLE media ADD COLUMN headline TEXT;
