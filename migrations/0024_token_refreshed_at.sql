--
-- شاشةُ المنصّة تقول متى رُبط الحساب (`accounts.created_at`) ومتى ينتهي
-- رمزُه (`tokens.expires_at`) ومتى اقترب من الانتهاء (`token_alerts`)،
-- **ولا تقول متى جُدّد آخرَ مرّةٍ بنجاح** — و`updated_at` تُكتب عند الربط
-- والتجديد معا فلا تفرّق بينهما.
--
-- فعمودٌ يُختَم عند التجديد الناجح وحده، ويبقى فارغا لحسابٍ لم يُجدَّد قطّ.
-- **والترحيلُ قبل الدالّة** (CLAUDE.md).
