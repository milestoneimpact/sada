-- بصمةُ الموافقة لصفحات LinkedIn (مراجعة D-425): الصفحاتُ التي اختيرت في موافقةٍ واحدةٍ تحمل بصمتَها نفسَها.
--
-- ## لماذا
--
-- كان الفصلُ يسأل «أتحمل صفحةٌ أخرى الرمزَ نفسَه؟» بمقارنة `access_token` — والتجديدُ يجدّد كلَّ صفحةٍ وحدَها فتتباين رموزُها
-- بعد أوّل تجديد، فيُبطَل رمزُ المدير عند LinkedIn وصفحةٌ أخرى من الموافقة نفسِها ما زالت مربوطة.
--
-- ## ما يُضاف (إضافيٌّ خالص)
--
-- `accounts.grant_id`: ‏SHA-256 لرمز التجديد (أو رمز الوصول إن غاب) **ساعةَ الاختيار** — لا الرمزُ نفسُه، ولا يُفكّ إلى رمز.
-- وغيابُه (صفحاتٌ رُبطت قبله) يُعدّ مشتركًا مع أيّ صفحةٍ نشطةٍ أخرى: لا يُنادى الإبطالُ، والخطأُ في الاتّجاه الآمن.
--
-- يُطبَّق قبل نشر الشيفرة (الترحيلُ قبل الدالّة): الاختيارُ يكتب العمود، والفصلُ يقرؤه.

ALTER TABLE accounts ADD COLUMN grant_id TEXT;
