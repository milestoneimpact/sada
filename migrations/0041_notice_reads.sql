--
-- ## ما كان
--
-- الفشلُ لا يُعرَف إلّا بالبريد اليوميّ (`alert_outbox` حين يُضبط webhook) أو عند الدخول التالي إن صادف المالكُ
-- بطاقتَه. ولا أثرَ لما قُرئ: الإنذارُ نفسُه يُعاد في كلّ فتحة.
--
-- ## ما صار
--
-- الإشعاراتُ **تُشتقّ من الصفوف القائمة** (منشورٌ فاشل، وحسابٌ منقطع، وصورٌ تنتظر الحصّة، وإذنٌ يقترب، ودورةٌ
-- متأخّرة، وسقفٌ بُلغ) ولا تُكرَّر في جدول — فلا يُخترَع حدثٌ. وما يُحفظ هنا **ما قُرئ وحدَه**: مرجعُ الإشعار
-- (`ref` ثابتٌ لحدثه) ومتى قُرئ ومن قرأه، بمنظّمته. والإشعارُ يختفي حين يزول سببُه، وتزول علامتُه معه بعد أسبوعين.
CREATE TABLE notice_reads (
  ref      TEXT NOT NULL,
  org_id   TEXT NOT NULL DEFAULT 'org_owner',
  read_at  TEXT NOT NULL DEFAULT (datetime('now')),
  by_email TEXT,
  PRIMARY KEY (org_id, ref)
);
CREATE INDEX notice_reads_at ON notice_reads (org_id, read_at);
