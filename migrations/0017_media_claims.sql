-- حجزُ التوليد — **والقيدُ يمنع الصفَّ المكرّر، لا الدفعَ المكرّر.**
--
-- `media.idempotency_key` فريدٌ منذ `0010` (D-004). وهو يمنع صفّين
-- لنداءٍ واحد — **ويقع بعد أن يُدفَع ثمنُ النداءين**: الترتيبُ في
-- الشيفرة كان «اقرأ، ثمّ ولّد، ثمّ اكتب»، والقيدُ في آخره.
--
-- ## والفيديو أسوأُ من ذلك
--
-- حارسُه كان قراءةَ صفٍّ `ready` — **وهو لا يوجد إلّا بعد دقائق**:
-- التوليدُ والسحبُ والرفع. فالنافذةُ ليست سباقَ أجزاءٍ من الثانية، هي
-- **دقائقُ تُقبل فيها كلُّ نقرةٍ بتوليدٍ جديد**. ومفتاحُه كان
-- `video/{post}/{uuid}` — **فريدٌ لكلّ نداء**، فالقيدُ لا يقع أبدا.
--
-- **وهو أغلى ما يُنادى في النظام، وسعرُه لم يُقرأ بعد (M-16).**
--
-- ## فالحجزُ يسبق النداء
--
-- صفٌّ يُكتب **قبل** أن يُنفَق، ومفتاحُه هو مفتاحُ عدم التكرار نفسُه.
-- فمن كتبه ولّد، ومن رُدَّ عُلم أنّ نداءً جاريا — **والقاعدةُ تفصل
-- بينهما لا الشيفرة**.
--
-- وجدولٌ على حدة لا عمودُ حالةٍ في `media`: صفُّ `media` يصف بايتاتٍ
-- موجودة، وصفٌّ بلا بايتاتٍ فيه يكذب على كلّ من يقرأ الجدول.
CREATE TABLE media_claims (
  -- هو `media.idempotency_key` بعينه: من حجز كتب، ومن كتب حجز
  idempotency_key TEXT PRIMARY KEY,
  post_id    TEXT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  kind       TEXT NOT NULL CHECK (kind IN ('image', 'video')),
  -- **ويُقرأ ليُعرَف الشائخ**: نداءٌ مات دون أن يُحرِّر حجزَه لا يُقفل
  -- البابَ إلى الأبد
  claimed_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX idx_media_claims_post ON media_claims (post_id, claimed_at DESC);
