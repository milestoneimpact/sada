--
-- ## ١ · `backups` — سجلُّ كلِّ نسخةٍ احتياطيّةٍ أسبوعيّة
--
-- كانت القاعدةُ التي تحمل حساباتِ المالك الحقيقيّة (D-271) بلا نسخةٍ خارجها: Time Travel يعيدها إلى أيّ دقيقةٍ في ثلاثين يومًا
-- **في مكانها**، ولا شيءَ بعد ذلك ولا نسخةَ تُفتح في غيرها. فصارت دورةٌ يوميّةٌ (‏`3 3 * * *`) تأخذ نسخةً كلَّ سبعة أيّام من كلّ
-- جداول D1، مشفّرةً بـ AES-GCM بمفتاحٍ مشتقٍّ من `TOKEN_ENC_KEY` (HKDF، `info = backup-v1`)، إلى دلوِ R2 خاصٍّ (`BACKUP`)،
-- وتُبقي آخرَ ثمانٍ. **وكلُّ محاولةٍ صفٌّ هنا**: متى، وبأيّ حال، وكم جدولًا وصفًّا وبايتًا، وبأيّ مفتاح (`kid`، بصمةٌ لا تُعكَس)،
-- وكم استغرقت، وكم نسخةً قديمةً حُذفت. **ولا قيمةَ سرٍّ في صفٍّ**: `detail` رسالةُ عطلٍ مقصوصة، والمفتاحُ لا يُكتب أبدًا.
-- و«صحّة صدى» في اللوحة تقرأ آخرَه.
--
-- **بلا `org_id`**: النسخةُ للقاعدة كلِّها لا لمنظّمة، كما `heartbeats`.
CREATE TABLE backups (
  id         TEXT PRIMARY KEY,
  at         TEXT NOT NULL DEFAULT (datetime('now')),
  status     TEXT NOT NULL CHECK (status IN ('ok', 'failed')),
  -- مفتاحُ الكائن في الدلو (`snapshots/…`)، وفارغٌ لمحاولةٍ سقطت قبل أن تكتب
  object_key TEXT,
  -- ‏`rows` كلمةٌ في SQLite (نوافذُ الإطار)، فالأسماءُ بعدّها صريحة
  table_count INTEGER NOT NULL DEFAULT 0,
  row_count   INTEGER NOT NULL DEFAULT 0,
  byte_count  INTEGER NOT NULL DEFAULT 0,
  kid        TEXT,
  ms         INTEGER NOT NULL DEFAULT 0,
  pruned     INTEGER NOT NULL DEFAULT 0,
  detail     TEXT
);
CREATE INDEX idx_backups_at ON backups (status, at);

-- ## ٢ · `pulse_slots` — ما رآه المراقبُ الخارجيُّ في كلّ عشر دقائق
--
-- `/pulse` (D-320) يجيب ‏200 أو ‏503، ومراقبُ M-47 يسأله كلَّ خمس دقائق، **ولا أثرَ لجوابٍ واحدٍ في القاعدة**: فلا يُحسَب منه توافرٌ
-- على ثمانيةٍ وعشرين يومًا. فصار كلُّ سؤالٍ يكتب خانةَ عشرِ دقائقه (`slot`، UTC) مرّةً في كلّ نسخةٍ من الـ Worker: `ok = 1` حين
-- ردّ ‏200، و`0` إن ردّ ‏503 ولو مرّةً في الخانة (`min`). **والخانةُ التي لا صفَّ لها لم يصلنا فيها أحد**: Worker واقف، أو شبكةٌ
-- لا تبلغه، أو المراقبُ نفسُه — فتُعدّ غيابًا لا حضورًا، وهو الاتّجاهُ المتحفّظ. وما فوق خمسةٍ وثلاثين يومًا يُمحى في الدورة اليوميّة.
CREATE TABLE pulse_slots (
  slot TEXT PRIMARY KEY,
  ok   INTEGER NOT NULL CHECK (ok IN (0, 1)),
  at   TEXT NOT NULL DEFAULT (datetime('now'))
);
