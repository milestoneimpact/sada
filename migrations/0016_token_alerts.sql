-- تنبيهُ انتهاء الرمز — **يُسجَّل لأنّه لا يُقاس بغير ذلك.**
--
-- ## البندُ الذي وسمتُه «لا يُقاس»
--
-- بوّابةُ المرحلة ٢ تشترط «تنبيهَ انتهاء رمزٍ وصل قبل أسبوع» (PLAN.md).
-- وD-064 وسمه `unmeasured` **وسببُه أنّه كان بريدا لا نقرؤه** — لا أنّ
-- القياسَ مستحيل.
--
-- **فالعلاجُ نقلُ التنبيه إلى حيث يُقاس**، لا الاعترافُ بأنّه لا يُقاس.
--
-- ## ولماذا صفٌّ ولا يُحسَب عند العرض
--
-- «انتهى قبل أسبوع» **يُحسَب من `expires_at` في أيّ لحظة**. لكنّ
-- البوّابة تسأل: **أوقع تنبيهٌ فعلا؟** — وذاك حدثٌ في الزمن، لا حالٌ
-- تُقرأ. وحسابُه عند العرض يجعل البوّابةَ تُجتاز **بمجرّد أن يقترب
-- رمزٌ من الانتهاء**، ولو لم يُنبَّه أحد.
--
-- ## والصفُّ فريدٌ بالحساب والعتبة
--
-- فدورةٌ تدور كلَّ يومٍ لا تكتب سبعةَ صفوفٍ لرمزٍ واحد. **والعتبةُ جزءٌ
-- من المفتاح**: تنبيهُ السبعةِ أيّام غيرُ تنبيه اليوم الواحد، وكلاهما
-- يستحقّ أن يقع.
--
-- ولا يُحذَف الصفُّ عند التجديد: **هو أثرُ ما وقع**، وسجلٌّ يُمحى عند
-- إصلاح العطل لا يشهد على شيء.

CREATE TABLE token_alerts (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  account_id  TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  -- أيُّ رمزٍ يقترب: الوصول أم التجديد. والتجديدُ أخطر — سقوطُه يوجب
  -- دورةَ إذنٍ كاملةً بيد المالك، وسقوطُ الوصول يُصلحه التجديدُ وحده
  kind        TEXT NOT NULL CHECK (kind IN ('access', 'refresh')),
  -- كم يوما بقي حين وقع التنبيه — ٧ أو ١
  threshold   INTEGER NOT NULL,
  expires_at  TEXT NOT NULL,
  at          TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE (account_id, kind, threshold, expires_at)
);

CREATE INDEX idx_token_alerts_at ON token_alerts (at);
