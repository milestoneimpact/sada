-- التقريرُ الأسبوعيّ وتوصيةُ الترويج — **بوّابةُ المرحلة ٣**.
--
-- نصُّها في `docs/PLAN.md`: «تقريرٌ أسبوعيٌّ وصل، وتوصيةُ ترويجٍ ظهرت
-- **مع تكلفتها** ولم يُنفَق شيء».
--
-- ## لماذا يُحفَظ التقريرُ ولا يُحسَب عند الطلب
--
-- **لأنّه يشهد على وقتٍ مضى.** التقريرُ يقول «هذا ما كان في ذلك
-- الأسبوع» — وحسابُه عند الفتح يجعله يقول ما هو الآن. والمقاييسُ
-- تتراكم بعد الأسبوع، فتقريرٌ يُعاد حسابُه في تشرين **يبدّل رقمَ
-- أيلول بأثرٍ رجعيّ**، فلا يُعرَف أنُميت الحصادُ أم أُعيد الحساب.
--
-- فيُكتب مرّةً ويُقرأ كما كُتب.
--
-- ## و`body_json` لا أعمدة
--
-- بنيةُ التقرير ستتبدّل — تُضاف منصّةٌ أو نافذةٌ أو سطر. وترحيلٌ لكلّ
-- تبديلٍ يعني **إعادةَ بناءِ صفوفٍ قديمةٍ بمعنى جديد**، وهو عينُ ما
-- يمنعه السببُ أعلاه. فيُحفَظ الجسدُ كما وُلد، ويُقرأ بنسخته.

CREATE TABLE reports (
  -- **مفتاحُه أوّلُ يومٍ في الأسبوع** لا معرّفٌ عشوائيّ: دورةٌ تعمل
  -- مرّتين — إعادةُ محاولةٍ أو جدولٌ يلتقي — تكتب الصفَّ نفسَه ولا
  -- تُنشئ تقريرا ثانيا للأسبوع نفسِه (D-004: التكرارُ يُمنَع بالمفتاح)
  id         TEXT PRIMARY KEY,
  from_at    TEXT NOT NULL,
  to_at      TEXT NOT NULL,
  -- نسخةُ البنية: قارئٌ يجد رقما لا يعرفه يقول ذلك ولا يخمّن
  version    INTEGER NOT NULL DEFAULT 1,
  body_json  TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX idx_reports_from ON reports (from_at);

