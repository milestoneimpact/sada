-- علاماتُ الأصل (D-346 · FLOW-PLAN المرحلة ٤) — **المفضّلةُ والوسوم** لصورةٍ أو مقطعٍ في مكتبة العميل.
--
-- المكتبةُ تكبر مع كلّ خطّة: عشراتُ الصور المولَّدة والمرفوعة، ولا يُعثر فيها إلّا بالتاريخ والنوع. فهذا الجدولُ يحمل ما يكتبه المالك
-- عن الأصل ليجده: مفضّلةٌ ووسوم.
--
-- **المفتاحُ كائنُ R2 لا صفُّ المنشور**: الصورةُ الواحدةُ تُربط بمنشوراتٍ كثيرة (صفٌّ في `media` لكلٍّ، D-334) وعلامتُها واحدة.
-- **إضافيٌّ خالص**: لا عمودَ يتغيّر في جدولٍ قائم، والشيفرةُ تقرؤه بـ`catch` — فقاعدةٌ لم تُرحَّل بعدُ تعرض المكتبةَ بلا علامات.
-- والوسومُ نصٌّ واحدٌ يفصله سطر: قليلةٌ (ثمانيةٌ على الأكثر) تُقرأ مع الأصل، ولا تُسأل وحدَها.
CREATE TABLE asset_marks (
  org_id     TEXT NOT NULL DEFAULT 'org_owner',
  r2_key     TEXT NOT NULL,
  favourite  INTEGER NOT NULL DEFAULT 0 CHECK (favourite IN (0, 1)),
  tags       TEXT NOT NULL DEFAULT '',
  updated_at TEXT NOT NULL DEFAULT (datetime('now')),
  PRIMARY KEY (org_id, r2_key)
);
