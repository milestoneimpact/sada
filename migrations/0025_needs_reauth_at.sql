-- ختمُ سقوط الإذن — **متى سقط، لا أنّه سقط فقط** (D-131).
--
-- `accounts.status = 'needs_reauth'` تقول إنّ الرمزَ رُدّ أو انتهى، ولا تقول
-- متى. وسجلُّ صحّة الحساب (D-129) كان يقرأ السقوطَ من الحال ومن تنبيه
-- الانتهاء، **ولا تاريخَ له** — ومالكٌ يعود بعد أسبوع لا يعرف أسقط أمسِ أم
-- قبل شهر، ولا كم منشورا مجدولا مرّ عليه ساقطا.
--
-- فعمودٌ يُختَم عند التعليم، ويُمحى عند إعادة الربط: `NULL` تعني «قائم».
-- **والترحيلُ قبل الدالّة** (CLAUDE.md).
ALTER TABLE accounts ADD COLUMN needs_reauth_at TEXT;
