-- بوّابةُ المحاولات الذرّيّة — **تُحجَز المحاولةُ قبل أن يُتحقَّق منها** (D-161).
--
-- حدُّ المحاولات كان في KV: يُقرأ العدّادُ، ثمّ يُتحقَّق من الرمز، ثمّ يُكتب
-- العدّادُ زائدًا واحدًا. **وبين القراءة والكتابة نافذة**: ألفُ طلبٍ متزامنٍ
-- إلى `/panel/2fa/totp` يقرأ كلُّها «صفر» قبل أن يكتب أحدُها، فيُفحَص ألفُ
-- تخمينٍ بدل خمسة. ورمزُ التطبيق ستُّ خاناتٍ بانحرافٍ ±١ — فمن يملك كلمةَ
-- الإدارة (وهو التهديدُ الذي يصدّه العاملُ الثاني) يكسره في ساعات.
--
-- وD1 كاتبٌ واحد: `INSERT … ON CONFLICT … RETURNING n` ذرّيٌّ، فالطلبُ
-- العاشرُ يرى عشرة ولو وصلت العشرةُ معًا. والنافذةُ ربعُ ساعةٍ تبدأ من أوّل
-- محاولةٍ فيها. وKV يبقى لما يقوله للمالك («بقيت محاولتان»)، وهذا للحدّ.
-- **والترحيلُ قبل الدالّة** (CLAUDE.md).
CREATE TABLE auth_attempts (
  -- `ip:<عنوان>` و`global` للتحقّق، و`challenge:<عنوان>` و`challenge:global`
  -- لإصدار تحدّيات مفتاح المرور (كلُّ تحدٍّ كتابةٌ مدفوعةٌ في KV)
  bucket TEXT PRIMARY KEY,
  n INTEGER NOT NULL,
  window_start TEXT NOT NULL
);
