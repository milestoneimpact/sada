-- **الرفضُ يُخلي الاسم — والصفوفُ التي رُفضت قبل D-087 لم تُخلِه** (D-088).
--
-- D-087 غيّرت الكاتب: كلُّ رفضٍ **جديد** يوسم `idempotency_key` بمعرّف
-- الصفّ، فيبقى الصفُّ بكلفته في الدفتر **ويُخلى الاسمُ لتوليدٍ بديل**.
--
-- **ولم تُصلِح ما وقع قبلها.** فصفٌّ رُفض قبل ذلك التاريخ يحمل مفتاحَه
-- نظيفا، والقيدُ `UNIQUE` عليه منذ ‏0010 — فالإدراجُ البديل يصطدم به،
-- والخطوةُ ٢ في `generateForPost` تجده فتقول «وُلّدت صورةٌ لهذا النصّ»
-- **بلونٍ أخضر**، ولا صورة.
--
-- وهو ما شكا منه المالك بالحرف: «يظهر أنّها تمّت، ولم تتمّ».
--
-- **والترحيلُ قبل الدالّة**: الشيفرةُ الجديدة تقرأ الحال لا الاسم، ولكن
-- الاسمَ المشغولَ يبقى يصطدم بالقيد ما لم يُخلَ هنا.
UPDATE media
   SET idempotency_key = idempotency_key || ':rejected:' || id
 WHERE status = 'rejected'
   AND idempotency_key NOT LIKE '%:rejected:%';
