-- «احذف وأعد النشر» مرّةً واحدة للمنشور (مراجعة D-396).
--
-- ## ما يُضاف (إضافيٌّ خالص)
--
-- - `posts.replace_claim`: معرّفُ التصحيح (`post_corrections.id`) الذي يحذف هذا المنشورَ ويعيد نشره الآن.
--   يُحجز بتحديثٍ مشروط قبل أوّل DELETE، فتصحيحان متزامنان بمفتاحين مختلفين لا يحذفان معًا ولا يدفعان البديلَ مرّتين.
--   ويُفكّ الحجزُ ضمنًا حين يصير ذلك التصحيحُ `failed` (الحجزُ يُقبل فوق تصحيحٍ فاشل).
--
-- يُطبَّق قبل نشر الشيفرة: `correct.ts` يكتب العمودَ قبل الحذف.

ALTER TABLE posts ADD COLUMN replace_claim TEXT;
