/**
 * يكتب صفحةً للتدقيق — **بخطِّها الحقيقيّ مضمَّنا** (D-099).
 *
 * ## ولولا هذا لقاس المدقّقُ خطًّا لا يراه المالك
 *
 * صار الخطُّ يُخدَم من `/f/…` في أصلنا. **والمدقّقُ يفتح `file://`**، فلا
 * أصلَ هناك ولا مسار — فيسقط المتصفّح إلى خطٍّ بديل.
 *
 * وهذا يُفسد **أدقَّ ما يقيسه**: طولُ السطر محدودٌ بـ`--measure` بوحدة
 * `ch` — **وهي عرضُ الرقم «0» في الخطّ المحمَّل**. فخطٌّ بديلٌ أعرضُ
 * يعطي سطرا أقصرَ محرفا فيمرّ ما يجب أن يسقط، وأضيقُ يعطي أطولَ فيسقط
 * ما يجب أن يمرّ.
 *
 * **وهي عينُ القاعدة المكتوبة في `tokens.ts`**: «الأرقامُ تُقاس عند كلّ
 * تبديلِ خطّ، ولا تُنقَل» — ولا يُقاس بخطٍّ غيرِ الذي يُشحن.
 *
 * ## و`data:` هنا لا في الإنتاج
 *
 * الضمُّ في الوثيقة يدفع ‏١٠٣KB مع كلّ فتحة، ولذلك بُني المسار. **وملفُّ
 * التدقيق يُفتَح مرّةً ويُرمى**، فالضمُّ فيه صواب.
 *
 * **ووزنُ الصفحة يُقاس قبل الضمّ**: `audit_mobile` يقرأ حجمَ الملفّ، وضمُّ
 * ‏١٤٠KB يجعله يتّهم صفحةً وزنُها الحقيقيُّ دونها. فيُكتب ملفّان: مضمومٌ
 * للقياس البصريّ، ومجرّدٌ لقياس الوزن.
 */
import { writeFileSync } from 'node:fs'
import { FACES } from '../src/lib/ui/fonts'
import { STYLE_BODY, STYLE_PATH } from '../src/lib/ui/asset'

export function writeAudited(path: string, html: string): void {
  /*
   * **وورقةُ الأنماط تُضَمّ كذلك** (D-101).
   *
   * خرجت إلى `/a/…`، **والمدقّقُ يفتح ملفّا محلّيّا** فلا أصلَ هناك ولا
   * مسار. فيقيس صفحةً بلا أنماطٍ أصلا — **ويعطي «صفرا» على كلّ شيء**:
   * لا هدفَ لمسٍ صغير، ولا سطرَ طويل، ولا فيضَ أفقيّ. **وصفرٌ من العدم
   * أخطرُ من ملحوظة.**
   *
   * وهي علّةُ الخطّ نفسُها في D-099، وقد وقعت مرّةً — فتُغلَق ههنا معه.
   */
  let inlined = html.replace(
    `<link rel="stylesheet" href="${STYLE_PATH}">`,
    `<style>${STYLE_BODY}</style>`,
  )
  for (const face of FACES) {
    inlined = inlined.replace(
      `url('${face.path}')`,
      `url('data:font/woff2;base64,${face.b64}')`,
    )
  }
  // والسبقُ يُحذَف: مسارٌ لا يُحلّ من `file://` يعطي خطأ شبكةٍ في السجلّ
  inlined = inlined.replace(/<link rel="preload" as="font"[^>]*>\n?/g, '')

  writeFileSync(path, inlined)
  // والمجرّدُ بجانبه — يقرؤه مدقّقُ الوزن وحدَه
  writeFileSync(path.replace(/\.html$/, '.bare.html'), html)
}
